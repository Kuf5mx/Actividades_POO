package actividad2.erick.garcia.proceso;

public class Resta {

    /**
     * Resta el segundo operando al primero.
     *
     * @param op1 minuendo
     * @param op2 sustraendo
     * @return diferencia: op1 - op2
     */
    public static int realizarOperacion(int op1, int op2) {
        return op1 - op2;
    }
}