package actividad2.erick.garcia.proceso;

public class Suma {
    /**
     * Suma dos valores enteros y devuelve el resultado.
     * Se usa como operación básica para otras funciones.
     *
     * @param op1 primer sumando
     * @param op2 segundo sumando
     * @return la suma de op1 y op2
     */
    public static int realizarOperacion(int op1, int op2) {
        return op1 + op2;
    }
}